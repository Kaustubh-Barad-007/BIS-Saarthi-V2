// Helper to get translated string with fallback chain
export const getTranslation = (key, lang = 'en') => {
  if (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) {
    return TRANSLATIONS[lang][key]
  }
  if (TRANSLATIONS.en && TRANSLATIONS.en[key]) {
    return TRANSLATIONS.en[key]
  }
  return key
}

// React hook for easy reactive translation across any component
export function useTranslation() {
  const preferredLanguage = useSettingsStore((s) => s.preferredLanguage) || 'en'
  const setPreferredLanguage = useSettingsStore((s) => s.setPreferredLanguage)

  const t = (key, fallback) => {
    const val = getTranslation(key, preferredLanguage)
    if (val && val !== key) return val
    return fallback || key
  }

  return {
    t,
    language: preferredLanguage,
    setLanguage: setPreferredLanguage,
  }
}

export default useTranslation
